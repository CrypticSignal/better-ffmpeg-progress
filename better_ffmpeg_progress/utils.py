import os
import re
import shutil
import subprocess
from collections import deque
from pathlib import Path
from typing import Dict, List, Optional

from .exceptions import FfmpegCommandError

_FFMPEG_INPUT_FLAG = "-i"
_OUT_TIME_US_PREFIX = b"out_time_us="
_TOTAL_SIZE_PREFIX = b"total_size="
_BYTES_PER_MB = 1024 * 1024
_MULTIPLIER = 1e-6


# A protocol prefix such as "pipe:", "rtsp://" or "concat:". At least two characters are required
# before the colon, so that a Windows drive letter (e.g. "C:\\video.mp4") is not matched.
_PROTOCOL_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9+.-]+:")
# A printf-style pattern used for image sequences, e.g. "img%03d.png".
_SEQUENCE_PATTERN_RE = re.compile(r"%0?\d*d")


def get_input_format(command: List[str], input_flag_pos: int) -> Optional[str]:
    """
    Returns the value of the "-f" option given for the first input (e.g. "lavfi" for
    "-f lavfi -i testsrc2"), or None if no input format is specified.
    """
    input_format = None
    args = command[1:input_flag_pos]
    for i, arg in enumerate(args[:-1]):
        if arg == "-f":
            input_format = args[i + 1]
    return input_format


def is_lavfi_input(command: List[str], input_flag_pos: int) -> bool:
    """
    Returns True if the first input's format is "lavfi", meaning it is a filtergraph
    (e.g. "testsrc2=duration=30") generated by FFmpeg rather than a file or URL.
    """
    return get_input_format(command, input_flag_pos) == "lavfi"


def is_stdin_input(input_file: str) -> bool:
    """Returns True if the input is read from standard input or a file descriptor."""
    return input_file == "-" or input_file.startswith("pipe:")


def is_protocol_input(input_file: str) -> bool:
    """Returns True if the input uses a protocol, e.g. "https://...", "rtsp://..." or "pipe:0"."""
    return bool(_PROTOCOL_RE.match(input_file))


def is_local_file_input(command: List[str], input_flag_pos: int) -> bool:
    """
    Returns True if the first input is expected to be a path to an existing local file.
    Inputs read from standard input, inputs with a protocol (e.g. a URL), and inputs with an
    explicit format (e.g. "-f lavfi", "-f v4l2" or "-f concat") are not.
    """
    input_file = command[input_flag_pos + 1]
    return not (
        is_stdin_input(input_file)
        or is_protocol_input(input_file)
        or get_input_format(command, input_flag_pos) is not None
    )


def validate_ffmpeg_command(command: List[str]) -> None:
    """
    Validates the FFmpeg command.
    Raises FfmpegCommandError if validation fails.
    """
    if not command:
        raise FfmpegCommandError("FFmpeg command list cannot be empty.")

    ffmpeg_executable = command[0]
    if not shutil.which(ffmpeg_executable):
        err_msg = (
            f"'{ffmpeg_executable}' not found. "
            "Ensure it's in your system's PATH or provide the full path of the FFmpeg executable."
        )

        raise FfmpegCommandError(err_msg)

    if _FFMPEG_INPUT_FLAG not in command:
        raise FfmpegCommandError(
            f"FFmpeg command must include the input flag '{_FFMPEG_INPUT_FLAG}'."
        )

    try:
        input_flag_pos = command.index(_FFMPEG_INPUT_FLAG)
    except ValueError:
        raise FfmpegCommandError(
            f"Internal error: Input flag '{_FFMPEG_INPUT_FLAG}' not found after check."
        )

    input_file_idx = input_flag_pos + 1
    if input_file_idx >= len(command):
        raise FfmpegCommandError(f"No input file specified after '{_FFMPEG_INPUT_FLAG}'.")

    input_file = command[input_file_idx]
    if input_file.startswith("-") and len(input_file) == 2 and not input_file[1:].isdigit():
        raise FfmpegCommandError(
            f"Input file path '{input_file}' looks like an option flag. Please check your command."
        )

    # Validate the input. Only local file paths can be checked: inputs such as standard input,
    # network streams, devices and lavfi filtergraphs are left for FFmpeg to validate.
    if (
        is_local_file_input(command, input_flag_pos)
        and not Path(input_file).exists()
        and not _SEQUENCE_PATTERN_RE.search(input_file)
    ):
        raise FfmpegCommandError(f"Input file not found: {input_file}")

    if len(command) <= input_file_idx + 1:
        raise FfmpegCommandError(
            "No output file specified. The command seems to end after the input file path."
        )

    output_file_path_str = command[-1]
    if output_file_path_str == input_file and is_local_file_input(command, input_flag_pos):
        raise FfmpegCommandError(
            "Output file path cannot be the same as the input file path in this command structure."
        )


def get_media_duration(input_file: str) -> Optional[float]:
    """
    Retrieves the duration of a media file or URL using ffprobe.
    Returns duration in seconds, or None if it cannot be determined.
    Accepts input_file as a string to correctly handle URLs.
    """
    if not shutil.which("ffprobe"):
        print("Warning: ffprobe not found in PATH. Cannot determine media duration.")
        return None
    try:
        output = subprocess.check_output(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_entries",
                "format=duration",
                "-of",
                "default=noprint_wrappers=1:nokey=1",
                "-i",
                input_file,
            ],
            text=True,
            stderr=subprocess.DEVNULL,
        )
        return float(output)
    except (subprocess.CalledProcessError, ValueError, FileNotFoundError):
        print(f"Warning: Could not determine duration for '{input_file}'.")
        return None


def parse_ffmpeg_progress_line(
    line: bytes, total_duration_secs: Optional[float]
) -> Optional[float]:
    """
    Parses a progress line from FFmpeg's stdout.
    Example line: b"out_time_us=12345678"
    Returns the current progress time in seconds, or None if parsing fails or line is not a progress line.
    Caps progress at total_duration_secs if provided.
    Assumes `line` has already been stripped of leading/trailing whitespace.
    """
    if line.startswith(_OUT_TIME_US_PREFIX):
        try:
            # Get the value after out_time_us=
            value_str = line[len(_OUT_TIME_US_PREFIX) :]

            if not value_str:
                return None

            current_time_us = int(value_str)
            current_time_secs = current_time_us * _MULTIPLIER

            if total_duration_secs is not None:
                return min(current_time_secs, total_duration_secs)
            return current_time_secs
        except (ValueError, IndexError):
            return None

    return None


# Matches FFmpeg's time duration syntax: [-][HH:]MM:SS[.m...] or [-]S+[.m...][s|ms|us]
_SEXAGESIMAL_RE = re.compile(r"^(-)?(?:(\d+):)?(\d+):(\d+(?:\.\d*)?)$")
_SECONDS_RE = re.compile(r"^(-)?(\d+(?:\.\d*)?|\.\d+)(s|ms|us)?$")
_TRIM_OPTIONS = ("-ss", "-sseof", "-t", "-to")


def parse_ffmpeg_time(value: str) -> Optional[float]:
    """
    Parses a time duration in FFmpeg's syntax (e.g. "90", "1.5", "500ms", "01:30", "00:01:30.5").
    Returns the value in seconds, or None if it cannot be parsed.
    """
    value = value.strip()

    match = _SEXAGESIMAL_RE.match(value)
    if match:
        sign, hours, minutes, seconds = match.groups()
        total = int(hours or 0) * 3600 + int(minutes) * 60 + float(seconds)
        return -total if sign else total

    match = _SECONDS_RE.match(value)
    if match:
        sign, number, unit = match.groups()
        total = float(number) / {None: 1, "s": 1, "ms": 1e3, "us": 1e6}[unit]
        return -total if sign else total

    return None


def _collect_trim_options(args: List[str]) -> Dict[str, float]:
    """Returns the last value of each trim option found in args (FFmpeg uses the last occurrence)."""
    options: Dict[str, float] = {}
    for i, arg in enumerate(args[:-1]):
        if arg in _TRIM_OPTIONS:
            parsed = parse_ffmpeg_time(args[i + 1])
            if parsed is not None:
                options[arg] = parsed
    return options


def _apply_trim(duration: float, options: Dict[str, float]) -> float:
    """
    Applies -ss/-sseof/-t/-to to a duration, mirroring FFmpeg's logic:
    -t takes priority over -to, and -to is relative to -ss (recording_time = to - ss).
    """
    start = options.get("-ss", 0.0)

    if "-sseof" in options and "-ss" not in options:
        # -sseof is negative, relative to the end of the input
        remaining = min(duration, abs(options["-sseof"]))
    else:
        remaining = duration - max(start, 0.0)

    if "-t" in options:
        remaining = min(remaining, options["-t"])
    elif "-to" in options:
        remaining = min(remaining, options["-to"] - max(start, 0.0))

    return max(remaining, 0.0)


def get_expected_output_duration(command: List[str], input_duration: float) -> float:
    """
    Estimates the duration of the output by taking the trim options of the command into account.

    Options before the first "-i" are input options for the first input, and options between the
    last input path and the output path are output options. Input trimming is applied first
    (seeking with an input -ss resets timestamps to 0), then output trimming.

    If -copyts is used, timestamps are not reset, so no adjustment is made.
    """
    if "-copyts" in command:
        return input_duration

    first_input_idx = command.index(_FFMPEG_INPUT_FLAG)
    last_input_idx = len(command) - 1 - command[::-1].index(_FFMPEG_INPUT_FLAG)

    input_options = _collect_trim_options(command[1:first_input_idx])
    output_options = _collect_trim_options(command[last_input_idx + 2 : -1])

    duration = _apply_trim(input_duration, input_options)
    duration = _apply_trim(duration, output_options)

    # Never return 0, which would disable the progress bar.
    return duration if duration > 0 else input_duration


def parse_ffmpeg_total_size_line(line: bytes) -> Optional[float]:
    """
    Parses a total_size line from FFmpeg's stdout.
    Example line: b"total_size=12345678"
    Returns the current output size in MB, or None if parsing fails or line is not a total_size line.
    Assumes `line` has already been stripped of leading/trailing whitespace.
    """
    if line.startswith(_TOTAL_SIZE_PREFIX):
        try:
            value_str = line[len(_TOTAL_SIZE_PREFIX) :]

            if not value_str:
                return None

            return int(value_str) / _BYTES_PER_MB
        except ValueError:
            return None

    return None


def truncate_filename(filename: str, max_length: int = 60) -> str:
    """
    Truncates a filename to at most max_length characters, preserving the file extension.
    """
    if len(filename) <= max_length:
        return filename

    stem, ext = os.path.splitext(filename)
    ellipsis = "..."
    allowed_stem_len = max_length - len(ext) - len(ellipsis)

    if allowed_stem_len < 1:
        return filename[: max_length - len(ellipsis)] + ellipsis

    return f"{stem[:allowed_stem_len]}{ellipsis}{ext}"


def estimate_final_size_mb(
    current_size_mb: float, current_time_secs: float, total_duration_secs: float
) -> Optional[float]:
    """
    Estimates the final output size in MB by extrapolating the current size over the total duration.
    Returns None until enough of the input has been processed for the estimate to be meaningful.
    """
    min_secs = max(1.0, total_duration_secs * 0.01)
    if current_time_secs < min_secs or current_size_mb <= 0:
        return None
    return current_size_mb / current_time_secs * total_duration_secs


def build_failure_message(log_file: object, max_lines: int = 5) -> str:
    """
    Returns the error message for a failed FFmpeg process, including the last lines of the
    FFmpeg log when it was written to a file path.
    """
    message = f"FFmpeg process failed. Check '{log_file}' for details."
    if not isinstance(log_file, Path):
        return message

    try:
        with open(log_file, encoding="utf-8", errors="replace") as f:
            tail = [line.rstrip() for line in deque(f, maxlen=max_lines) if line.strip()]
    except OSError:
        return message

    if not tail:
        return message
    return message + " Last lines of the log:\n" + "\n".join(tail)
